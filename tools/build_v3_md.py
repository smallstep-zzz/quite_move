def build_screening(recs):
    lines = [
        "# 파트3 · 01 스크리닝 표 — 비상장 초기투자 스타트업 그리드",
        "",
        f"기준일: {G} · 판정: 투자 시그널 등급(A/A-/B+/B/C/D) · 매출·순익·사원수는 공개 데이터 부재로 `-` 표기.",
        "도메인별로 투자받은 비상장 기업을 골라 사업모델과 최근 라운드를 정렬한다.",
        "",
    ]
    order = DOMAIN_ORDER
    by = {}
    for r in recs:
        by.setdefault(r["도메인"], []).append(r)
    no = 0
    for dom in order:
        group = by.get(dom, [])
        if not group:
            continue
        lines.append(f"## {dom}")
        lines.append("")
        lines.append(f"> {DOMAIN_NOTE[dom]}")
        lines.append("")
        lines.append("| # | 기업 (법인명) | 설립 | 사업모델 | 최근 투자 라운드 | 판정 |")
        lines.append("|---|---|---|---|---|---|")
        for r in group:
            no += 1
            inv = I[r["브랜드"]]
            name = f"**{r['브랜드']}** ({r['사이트맵명']})"
            grade = inv["등급"]
            cum = inv["누적"]
            if cum.startswith("("):
                cum_txt = ""
            else:
                cum_txt = " · 누적 " + cum
            lines.append(
                f"| {no} | {name} | {r['설립일자'][:10]} | {r['수익모델추정']} | "
                f"{inv['라운드']}{cum_txt} | **{grade}** |"
            )
        lines.append("")
    lines.append("")
    lines.append("### 등급 분포")
    lines.append("")
    lines.append("| 등급 | 수 |")
    lines.append("|---|---|")
    from collections import Counter
    c = Counter(I[r["브랜드"]]["등급"] for r in recs)
    for k in ["A", "A-", "B+", "B", "C", "D"]:
        if c.get(k):
            lines.append(f"| **{k}** | {c[k]} |")
    lines.append("")
    return "\n".join(lines)


